use std::path::PathBuf;

use clap::{Parser, Subcommand, ValueEnum};

pub const DEFAULT_CLIENT_CONFIG_PATH: &str = "/usr/local/etc/rrp/rrpc.toml";
pub const DEFAULT_SERVER_CONFIG_PATH: &str = "/usr/local/etc/rrp/rrps.toml";

#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub enum RunMode {
    Client,
    Server,
}

impl RunMode {
    pub fn as_str(self) -> &'static str {
        match self {
            RunMode::Client => "client",
            RunMode::Server => "server",
        }
    }
}

#[derive(Debug, Parser)]
#[command(
    name = "rrp",
    version,
    about = "Simple, secure, high-performance reverse proxy with mlkem768x25519plus encryption and eBPF acceleration"
)]
pub struct Cli {
    #[command(subcommand)]
    pub command: Commands,
}

#[derive(Debug, Subcommand)]
pub enum Commands {
    /// Run rrp in server mode
    Server {
        /// Path to server configuration file
        #[arg(short, long, default_value = DEFAULT_SERVER_CONFIG_PATH)]
        config: PathBuf,
    },
    /// Run rrp in client mode
    Client {
        /// Path to client configuration file
        #[arg(short, long, default_value = DEFAULT_CLIENT_CONFIG_PATH)]
        config: PathBuf,
        /// Optional server address(es) to connect to (comma-separated or repeated)
        #[arg(short = 's', long = "server-addr", value_delimiter = ',')]
        server_addr: Vec<String>,
    },
    /// Generate mlkem768x25519 keypair (client) and optionally install system autostart service
    Install {
        /// Target mode for installation (client or server)
        #[arg(short, long, value_enum, default_value_t = RunMode::Client)]
        mode: RunMode,
        /// Path to configuration file (defaults to /usr/local/etc/rrp/rrpc.toml for client, /usr/local/etc/rrp/rrps.toml for server)
        #[arg(short, long)]
        config: Option<PathBuf>,
        /// Configure system-level autostart on boot (Linux systemd / macOS launchd)
        #[arg(long, default_value_t = false)]
        autostart: bool,
        /// Optional custom directory for service file output (defaults to /etc/systemd/system or /Library/LaunchDaemons)
        #[arg(long)]
        service_dir: Option<PathBuf>,
        /// Client mode only: discard the existing private key and generate a new keypair
        /// (the new public key must be approved on the server again)
        #[arg(long, default_value_t = false)]
        regenerate_key: bool,
    },
    /// Uninstall system autostart service and optionally purge binary and configuration files
    Uninstall {
        /// Target mode to uninstall (client or server; defaults to both if omitted)
        #[arg(short, long, value_enum)]
        mode: Option<RunMode>,
        /// Path to configuration file to remove when `--purge` is set
        #[arg(short, long)]
        config: Option<PathBuf>,
        /// Also delete the rrp binary itself and configuration file(s)
        #[arg(long, default_value_t = false)]
        purge: bool,
        /// Optional custom directory for service files (defaults to /etc/systemd/system or /Library/LaunchDaemons)
        #[arg(long)]
        service_dir: Option<PathBuf>,
    },
    /// Approve a client mlkem768x25519 public key and write it to server configuration
    Approve {
        /// Base64URL-encoded mlkem768x25519 public key generated by `rrp install`
        public_key: String,
        /// Path to server configuration file
        #[arg(short, long, default_value = DEFAULT_SERVER_CONFIG_PATH)]
        config: PathBuf,
    },
    /// Show live client/server connections, traffic, heartbeat, and uptime
    Status {
        /// Only show one runtime mode; by default, discover both client and server
        #[arg(short, long, value_enum)]
        mode: Option<RunMode>,
        /// Emit machine-readable JSON
        #[arg(long, default_value_t = false)]
        json: bool,
        /// Read a specific status snapshot file
        #[arg(long, value_name = "PATH")]
        file: Option<PathBuf>,
    },
}
